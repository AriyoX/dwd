// Exercises the real PostgREST/RPC path, with no R2 objects or production data.
// node --env-file=.tmp/e2e.env scripts/test-link-up-load.mjs
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import { z } from 'zod';

const url = process.env.E2E_SUPABASE_URL;
if (!url || !['localhost', '127.0.0.1'].includes(new URL(url).hostname))
  throw new Error('An isolated local Supabase backend is required.');
const db = createClient(url, process.env.E2E_SUPABASE_SECRET_KEY, {
  auth: { persistSession: false },
});
const sessions = Array.from({ length: 100 }, () => ({ id: randomUUID() }));
/** @type {number[]} */
const timings = [];
const reservations = z.array(z.object({ id: z.string() }));
/** @param {string} name @param {Record<string, unknown>} args @returns {Promise<unknown>} */
async function rpc(name, args) {
  const start = performance.now();
  const result = await db.rpc(name, args);
  timings.push(performance.now() - start);
  if (result.error) throw new Error(`${name}: ${result.error.message}`);
  return z.unknown().parse(result.data);
}
async function event() {
  const r = await db.from('photo_events').select('*').eq('slug', 'the-link-up').single();
  if (r.error) throw r.error;
  return z
    .object({
      storage_budget_bytes: z.number(),
      reserved_bytes: z.number(),
      used_bytes: z.number(),
    })
    .parse(r.data);
}
const before = await event();
assert.ok(
  before.storage_budget_bytes >= 9 * 1024 ** 3,
  'Apply the event capacity migration locally first.',
);
const started = performance.now();
try {
  // 2,200 maximum-size holds fit the 9 GiB event budget at the 4 MiB limit.
  // Additional photos fit as publication releases unused reservation capacity.
  for (const count of [10, 10, 2]) {
    const results = await Promise.allSettled(
      sessions.map(async (session) => {
        const batch = {
          p_session: session.id,
          p_batch: randomUUID(),
          p_files: Array.from({ length: count }, () => ({
            clientId: randomUUID(),
            fingerprint: 'a'.repeat(64),
            type: 'image/jpeg',
            size: 1000,
          })),
        };
        const uploads = reservations.parse(await rpc('link_up_reserve', batch));
        // Recovering the same batch must never reserve twice.
        const again = reservations.parse(await rpc('link_up_reserve', batch));
        assert.deepEqual(again.map((r) => r.id).sort(), uploads.map((r) => r.id).sort());
      }),
    );
    for (const result of results) if (result.status === 'rejected') throw result.reason;
  }
  const held = await event();
  assert.equal(held.reserved_bytes - before.reserved_bytes, 2200 * 4325376);
  assert.ok(held.used_bytes + held.reserved_bytes <= held.storage_budget_bytes);
  await rpc('link_up_reserve', {
    p_session: sessions[0].id,
    p_batch: randomUUID(),
    p_files: Array.from({ length: 3 }, () => ({
      clientId: randomUUID(),
      fingerprint: 'c'.repeat(64),
      type: 'image/jpeg',
      size: 4194304,
    })),
  });
  const extra = await db.rpc('link_up_reserve', {
    p_session: sessions[0].id,
    p_batch: randomUUID(),
    p_files: [
      { clientId: randomUUID(), fingerprint: 'b'.repeat(64), type: 'image/jpeg', size: 1000 },
    ],
  });
  assert.match(extra.error?.message ?? '', /session_quota/);
  timings.sort((a, b) => a - b);
  console.log(
    JSON.stringify({
      guests: 100,
      reservedPhotos: 2200,
      duplicateBatchRecoveries: 300,
      elapsedMs: Math.round(performance.now() - started),
      rpcP95Ms: Math.round(timings[Math.floor(timings.length * 0.95)]),
      rpcMaxMs: Math.round(timings.at(-1)),
      quotaEnforced: true,
    }),
  );
} finally {
  await cleanup();
}
async function cleanup() {
  // Each cleanup targets only UUIDs generated by this test invocation.
  for (const session of sessions) {
    const rows = await db
      .from('photo_upload_reservations')
      .select('id,temporary_key,final_key,thumbnail_key')
      .eq('session_id', session.id);
    if (rows.error) throw rows.error;
    const uploads = z
      .array(
        z.object({
          id: z.string(),
          temporary_key: z.string(),
          final_key: z.string(),
          thumbnail_key: z.string(),
        }),
      )
      .parse(rows.data);
    for (let i = 0; i < uploads.length; i += 10)
      await rpc('link_up_cancel', {
        p_session: session.id,
        p_ids: uploads.slice(i, i + 10).map((r) => r.id),
      });
    const keys = uploads.flatMap((r) => [r.temporary_key, r.final_key, r.thumbnail_key]);
    if (keys.length) {
      const removed = await db.from('photo_object_cleanup').delete().in('object_key', keys);
      if (removed.error) throw removed.error;
    }
    for (const [table, column] of [
      ['photo_upload_reservations', 'session_id'],
      ['photo_guest_sessions', 'id'],
    ]) {
      const removed = await db.from(table).delete().eq(column, session.id);
      if (removed.error) throw removed.error;
    }
  }
  const after = await event();
  assert.equal(after.reserved_bytes, before.reserved_bytes);
  assert.equal(after.used_bytes, before.used_bytes);
  console.log('Test reservations removed; storage counters restored.');
}
